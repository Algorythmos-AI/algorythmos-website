#!/usr/bin/env node
// scripts/build-land-mask.mjs
// One-off generator for the globe scene's land mask: a 180 × 90 grid (2° cells)
// saying which cells are land, packed to bits and base64-encoded into
// src/lib/scene3d/kit/land.ts (about 2.7 kB).
//
// Source: Natural Earth 1:110m land polygons (public domain), via the dev-only
// `world-atlas` package. Run again only if the grid resolution should change:
//   node scripts/build-land-mask.mjs

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'lib', 'scene3d', 'kit', 'land.ts');
const COLS = 180;
const ROWS = 90;

const topology = require('world-atlas/land-110m.json');
const land = feature(topology, topology.objects.land);
const polygons = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates));

/** Even-odd ray cast against one ring of [lon, lat] points. */
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
/** Outer ring minus holes. */
const inPolygon = (lon, lat, rings) => inRing(lon, lat, rings[0]) && !rings.slice(1).some((hole) => inRing(lon, lat, hole));

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let count = 0;
for (let row = 0; row < ROWS; row++) {
  const lat = 90 - (row + 0.5) * (180 / ROWS);
  for (let col = 0; col < COLS; col++) {
    const lon = -180 + (col + 0.5) * (360 / COLS);
    if (!polygons.some((rings) => inPolygon(lon, lat, rings))) continue;
    const n = row * COLS + col;
    bits[n >> 3] |= 1 << (n & 7);
    count++;
  }
}

const base64 = Buffer.from(bits).toString('base64');
const source = `/**
 * Land mask for the globe scene: ${COLS} × ${ROWS} cells (2° each), row 0 at the north
 * pole, column 0 at 180° W; one bit per cell, least-significant bit first.
 *
 * GENERATED by scripts/build-land-mask.mjs from Natural Earth 1:110m land
 * polygons (public domain). Do not edit by hand.
 */
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
const PACKED =
  '${base64.match(/.{1,100}/g).join("' +\n  '")}';

let bits: Uint8Array | null = null;

/** Is this point on land? Latitude and longitude in degrees. */
export function isLand(lat: number, lon: number): boolean {
  if (!bits) {
    const raw = atob(PACKED);
    bits = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i++) bits[i] = raw.charCodeAt(i);
  }
  const row = Math.min(LAND_ROWS - 1, Math.max(0, Math.floor(((90 - lat) / 180) * LAND_ROWS)));
  const col = ((Math.floor(((lon + 180) / 360) * LAND_COLS) % LAND_COLS) + LAND_COLS) % LAND_COLS;
  const n = row * LAND_COLS + col;
  return (bits[n >> 3] & (1 << (n & 7))) !== 0;
}
`;
fs.writeFileSync(OUT, source);
console.log(`${path.relative(ROOT, OUT)}: ${count} of ${COLS * ROWS} cells are land (${((count / (COLS * ROWS)) * 100).toFixed(1)}%), ${(source.length / 1024).toFixed(1)} kB`);
